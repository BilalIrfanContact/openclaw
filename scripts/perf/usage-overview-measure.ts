// Own synthetic state only. Run with node --import ./scripts/tsx.mjs.
// Times the Usage page overview (`sessions.usage`, projection "overview", all agents,
// family grouping, Asia/Kolkata) through an isolated Gateway process over the real WS
// protocol, counts work per thread, and checks totals against the fixture's ground truth.
import { spawn, type ChildProcess } from "node:child_process";
import { createWriteStream, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { setTimeout as delay } from "node:timers/promises";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { PROTOCOL_VERSION } from "../../packages/gateway-protocol/src/version.ts";
import { stopChild } from "../lib/gateway-bench-child.ts";
import {
  buildGatewayBenchChildArgs,
  createGatewayBenchEnv,
  summarizeNumbers,
} from "../lib/gateway-bench-runtime.ts";
import { createGatewayWsClient } from "../lib/gateway-ws-client.ts";

const { values } = parseArgs({
  options: {
    "state-dir": { type: "string" },
    entry: { type: "string", default: "dist/entry.js" },
    warm: { type: "string", default: "10" },
    cold: { type: "string", default: "5" },
    "converge-timeout-s": { type: "string", default: "3600" },
    label: { type: "string", default: "run" },
    "cpu-prof-dir": { type: "string" },
  },
});
if (!values["state-dir"]) {
  throw new Error("--state-dir is required (a state generated by usage-overview-fixture.ts)");
}
const root = path.resolve(values["state-dir"]);
const fixture = JSON.parse(readFileSync(path.join(root, "usage-overview-fixture.json"), "utf8"));
if (fixture.format !== "openclaw-usage-overview-fixture-v1") {
  throw new Error("--state-dir must be generated by scripts/perf/usage-overview-fixture.ts");
}
const port: number = fixture.port;
const output = path.join(root, `measure-${values.label}-${Date.now()}`);
mkdirSync(output);
const preload = fileURLToPath(new URL("./usage-overview-counts.mjs", import.meta.url));
const configPath = path.join(root, "openclaw.json");
const profileDir = values["cpu-prof-dir"] && path.resolve(values["cpu-prof-dir"]);
if (profileDir) {
  mkdirSync(profileDir, { recursive: true });
}

// The UI asks for the last 30 local days in Asia/Kolkata (+05:30; Asia/Calcutta is the
// same zone under another cache key).
const DAY = 86_400_000;
const zones = ["Asia/Kolkata", "Asia/Calcutta"];
const localDate = (ms: number) =>
  new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Kolkata",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(ms);
const endDate = localDate(fixture.now);
const startDate = localDate(fixture.now - 29 * DAY);
const startMs = Date.parse(`${startDate}T00:00:00+05:30`);
const endMs = Date.parse(`${endDate}T00:00:00+05:30`) + DAY - 1;
const truth = { tokens: 0, cost: 0, messages: 0, daily: new Map<string, number>() };
for (const [quarter, bucket] of Object.entries(fixture.truthQuarters) as Array<
  [string, { tokens: number; cost: number; messages: number }]
>) {
  const at = Number(quarter);
  if (at >= startMs && at <= endMs) {
    truth.tokens += bucket.tokens;
    truth.cost += bucket.cost;
    truth.messages += bucket.messages;
    truth.daily.set(localDate(at), (truth.daily.get(localDate(at)) ?? 0) + bucket.tokens);
  }
}
const params = (timeZone: string) => ({
  startDate,
  endDate,
  agentScope: "all",
  mode: "specific",
  timeZone,
  utcOffset: "UTC+5:30",
  groupBy: "family",
  limit: 50,
  projection: "overview",
});

let gateway: ChildProcess | undefined;
let client: ReturnType<typeof createGatewayWsClient> | undefined;
const counterReplies = new Map<number, (value: unknown) => void>();
let counterId = 0;
async function counters(
  action: "reset" | "profile-start" | "profile-stop" = "reset",
  name?: string,
) {
  const requestId = ++counterId;
  const reply = new Promise((resolve) => {
    counterReplies.set(requestId, resolve);
  });
  gateway!.send({ channel: "usage-overview-counters", action, requestId, name });
  return (await reply) as { main: Record<string, number>; workers: Record<string, number> };
}

async function startGateway(run: number) {
  const log = createWriteStream(path.join(output, `gateway-${run}.log`));
  const child = spawn(
    process.execPath,
    buildGatewayBenchChildArgs(values.entry!, port, ["--import", preload]),
    {
      detached: true,
      stdio: ["ignore", "pipe", "pipe", "ipc"],
      env: createGatewayBenchEnv(path.join(root, "home"), configPath, {
        startupTrace: false,
        caseEnv: {
          OPENCLAW_STATE_DIR: root,
          OPENCLAW_PROFILE: fixture.profile,
          TMPDIR: path.join(root, "tmp"),
          OPENCLAW_SKIP_CHANNELS: "1",
          OPENCLAW_SYSTEMD_UNIT: `openclaw-gateway-${fixture.profile}`,
          OPENCLAW_LAUNCHD_LABEL: `ai.openclaw.${fixture.profile}`,
          ...(profileDir ? { USAGE_OVERVIEW_PROFILE_DIR: profileDir } : {}),
        },
      }),
    },
  );
  child.on("message", (message: { channel?: string; requestId?: number }) => {
    if (message?.channel === "usage-overview-counters" && message.requestId) {
      counterReplies.get(message.requestId)?.(message);
      counterReplies.delete(message.requestId);
    }
  });
  child.stdout?.pipe(log);
  child.stderr?.pipe(log);
  let tail = "";
  let listening = false;
  const observe = (chunk: Buffer) => {
    tail = (tail + chunk.toString()).slice(-4096);
    listening ||= tail.includes("http server listening (");
  };
  child.stdout?.on("data", observe);
  child.stderr?.on("data", observe);
  gateway = child;
  const deadline = Date.now() + 180_000;
  for (;;) {
    if (child.exitCode !== null || child.signalCode !== null) {
      throw new Error(`Gateway exited: ${output}`);
    }
    if (Date.now() > deadline) {
      throw new Error(`Gateway readiness timed out: ${output}`);
    }
    if (
      listening &&
      (await fetch(`http://127.0.0.1:${port}/readyz`).then(
        (response) => response.ok,
        () => false,
      ))
    ) {
      break;
    }
    await delay(250);
  }
  const ws = createGatewayWsClient({ url: `ws://127.0.0.1:${port}` });
  await ws.waitOpen();
  const hello = await ws.request("connect", {
    minProtocol: PROTOCOL_VERSION,
    maxProtocol: PROTOCOL_VERSION,
    client: {
      id: "gateway-client",
      displayName: "usage-overview-measure",
      version: "1.0.0",
      platform: process.platform,
      mode: "backend",
    },
    role: "operator",
    scopes: ["operator.read", "operator.admin"],
    caps: [],
  });
  if (!hello.ok) {
    throw new Error(`connect failed: ${JSON.stringify(hello.error)}`);
  }
  client = ws;
}

async function stopGateway() {
  client?.close();
  client = undefined;
  if (gateway) {
    await stopChild(gateway, { teardownGraceMs: 10_000 });
    gateway = undefined;
  }
}

type UsageResult = {
  totals: { totalTokens: number; totalCost: number };
  aggregates: { costDaily?: Array<{ date: string; totalTokens: number }>; sessionCount?: number };
  cacheStatus?: { status: string; cachedFiles: number; pendingFiles: number; staleFiles: number };
  partial?: { reason: string; message: string };
};

async function usage(timeZone: string, measure = true) {
  if (measure) {
    await counters();
  }
  const started = performance.now();
  const response = await client!.request("sessions.usage", params(timeZone), 120_000);
  const wallMs = performance.now() - started;
  if (!response.ok) {
    throw new Error(`sessions.usage: ${JSON.stringify(response.error)}`);
  }
  const counts = measure ? await counters() : undefined;
  const payload = response.payload as UsageResult;
  const daily = payload.aggregates.costDaily ?? [];
  const dailyExact =
    daily.length === truth.daily.size &&
    daily.every((day) => truth.daily.get(day.date) === day.totalTokens);
  return {
    wallMs,
    responseBytes: JSON.stringify(payload).length,
    totalTokens: payload.totals.totalTokens,
    totalCost: payload.totals.totalCost,
    tokensExact: payload.totals.totalTokens === truth.tokens,
    // Cost is a float sum; addition order differs from the fixture's per-quarter order.
    costExact: Math.abs(payload.totals.totalCost - truth.cost) <= 1e-9 * truth.cost,
    dailyExact,
    sessionCount: payload.aggregates.sessionCount,
    cacheStatus: payload.cacheStatus,
    partial: payload.partial,
    counts,
  };
}

const results: Record<string, unknown> = {
  label: values.label,
  entry: values.entry,
  fixture: { ...fixture, truthQuarters: undefined },
  range: { startDate, endDate, startMs, endMs },
  truth: { ...truth, daily: Object.fromEntries(truth.daily) },
};
try {
  // Converge: startup refresh (or upgrade backfill) runs until no file is stale.
  await startGateway(0);
  const convergeStart = Date.now();
  const deadline = convergeStart + Number(values["converge-timeout-s"]) * 1000;
  let last = "";
  let stableSince = Date.now();
  for (;;) {
    const sample = await usage(zones[0]!, false);
    const key = JSON.stringify([sample.cacheStatus, sample.totalTokens, sample.partial?.reason]);
    if (key !== last) {
      last = key;
      stableSince = Date.now();
      console.log(
        JSON.stringify({ converge: Math.round((Date.now() - convergeStart) / 1000), ...sample }),
      );
    }
    if (sample.cacheStatus?.staleFiles === 0 && Date.now() - stableSince > 20_000) {
      break;
    }
    if (Date.now() > deadline) {
      throw new Error("Usage cache did not converge");
    }
    await delay(2_000);
  }
  results.convergeSeconds = (Date.now() - convergeStart) / 1000;
  const warm: Array<{ zone: string | undefined } & Awaited<ReturnType<typeof usage>>> = [];
  if (profileDir) {
    await counters("profile-start");
  }
  for (let index = 0; index < Number(values.warm); index++) {
    // A label edit advances the session revision, so each warm read recomputes the report
    // instead of returning the Gateway's cached snapshot.
    const patched = await client!.request("sessions.patch", {
      key: "agent:main:usage-session-0",
      label: `Usage fixture warm read ${index}`,
    });
    if (!patched.ok) {
      throw new Error(`sessions.patch: ${JSON.stringify(patched.error)}`);
    }
    warm.push({ zone: zones[index % 2], ...(await usage(zones[index % 2]!)) });
  }
  results.warm = warm;
  if (profileDir) {
    await counters("profile-stop", "warm");
  }
  await stopGateway();
  const cold: typeof warm = [];
  for (let run = 1; run <= Number(values.cold); run++) {
    await startGateway(run);
    // Let the startup refresh pass settle so the sample measures the cold report read.
    await delay(10_000);
    if (profileDir) {
      await counters("profile-start");
    }
    cold.push({ zone: zones[run % 2], ...(await usage(zones[run % 2]!)) });
    if (profileDir) {
      await counters("profile-stop", `cold-${run}`);
    }
    await stopGateway();
  }
  results.cold = cold;
  const median = (samples: typeof warm, pick: (sample: (typeof warm)[number]) => number) =>
    summarizeNumbers(samples.map(pick))?.p50;
  const summary = {
    label: values.label,
    sessions: fixture.sessions,
    exact: [...warm, ...cold].every(
      (sample) => sample.tokensExact && sample.costExact && sample.dailyExact && !sample.partial,
    ),
    warm: summarizeNumbers(warm.map((sample) => sample.wallMs)),
    cold: summarizeNumbers(cold.map((sample) => sample.wallMs)),
    warmCounts: Object.fromEntries(
      ["main", "workers"].flatMap((thread) =>
        [
          "sqlExec",
          "zstdDecompress",
          "sha256",
          "jsonParse",
          "bucketJsonParse",
          "workerPostMessage",
          "eluActiveMs",
          "cpuMs",
        ].map((name) => [
          `${thread}.${name}`,
          median(warm, (sample) => sample.counts![thread as "main" | "workers"][name] ?? 0),
        ]),
      ),
    ),
    convergeSeconds: results.convergeSeconds,
  };
  results.summary = summary;
  console.log(JSON.stringify({ summary }));
} catch (error) {
  results.error = String(error);
  throw error;
} finally {
  await stopGateway().catch(() => {});
  writeFileSync(path.join(output, "result.json"), `${JSON.stringify(results, null, 2)}\n`);
  console.log(JSON.stringify({ output }));
}
